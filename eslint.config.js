// @ts-check
import eslint from '@eslint/js';
import tseslint from 'typescript-eslint';

/**
 * `npm run lint` had no config at all, so it failed on every invocation with
 * "ESLint couldn't find an eslint.config.js" - a script in package.json that
 * could never have passed. CI never ran it, so nobody noticed.
 *
 * Type-aware rules are deliberately not enabled: `tsc -b` already runs in strict
 * mode with noUncheckedIndexedAccess across every package, so a second type
 * pass would cost minutes of CI to re-prove what the compiler proves. What is
 * left is the class of mistake the compiler does not catch.
 */
export default tseslint.config(
  {
    ignores: [
      '**/dist/**',
      '**/.next/**',
      '**/node_modules/**',
      '**/migrations/**',
      'contracts/**',
      '**/*.mjs',
      '**/*.js',
      // Generated by Next on every build.
      'apps/web/next-env.d.ts',
    ],
  },
  eslint.configs.recommended,
  ...tseslint.configs.recommended,
  {
    rules: {
      // Unused values are usually a half-finished edit. Leading underscore is
      // the documented opt-out, and the codebase already uses it for
      // deliberately-ignored parameters.
      '@typescript-eslint/no-unused-vars': [
        'error',
        { argsIgnorePattern: '^_', varsIgnorePattern: '^_', caughtErrors: 'none' },
      ],
      // `any` defeats the strictness the rest of the build depends on.
      '@typescript-eslint/no-explicit-any': 'error',
      // A floating promise in a worker tick is a silently swallowed failure.
      'no-console': 'off',
    },
  },
);
